
class Product {
  String productCode;
  String productName;
  String category;
  double price;
  int quantity;
  String image;
  String status;

  Product({
    required this.productCode,
    required this.productName,
    required this.category,
    required this.price,
    required this.quantity,
    required this.image,
    required this.status,
  });
}
